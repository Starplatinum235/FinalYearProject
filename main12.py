import streamlit as st
import pandas as pd
from PIL import Image
import subprocess
import os
import base64
import pickle

########################################
# Molecular descriptor calculation
########################################
def desc_calc():
    # Define absolute paths for PaDEL-Descriptor and descriptor files
    padel_jar = "/Users/muhammadali/PycharmProjects/pythonProject13/PaDEL-Descriptor/PaDEL-Descriptor.jar"
    fingerprint_xml = "/Users/muhammadali/PycharmProjects/pythonProject13/PaDEL-Descriptor/descriptors.xml"
    output_file = "/Users/muhammadali/PycharmProjects/pythonProject13/descriptors_output.csv"
    input_file = "/Users/muhammadali/PycharmProjects/pythonProject13/molecule.smi"

    # Remove old output file if it exists
    if os.path.exists(output_file):
        os.remove(output_file)

    # Construct the command to run PaDEL
    bashCommand = (
        f"java -Xms2G -Xmx2G -Djava.awt.headless=true "
        f"-jar {padel_jar} "
        f"-removesalt -standardizenitro -fingerprints "
        f"-descriptortypes {fingerprint_xml} "
        f"-dir /Users/muhammadali/PycharmProjects/pythonProject13/ "
        f"-file descriptors_output.csv"
    )
    # Run PaDEL-Descriptor
    process = subprocess.Popen(bashCommand.split(), stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    output, error = process.communicate()

    # Debug output
    st.write("PaDEL OUTPUT:", output.decode('utf-8'))
    st.write("PaDEL ERROR:", error.decode('utf-8'))

    # Check if the descriptors output file was created
    if not os.path.exists(output_file):
        st.error("PaDEL failed. Descriptors file not created.")
        st.stop()

    # Remove the temporary molecule.smi file
    if os.path.exists(input_file):
        os.remove(input_file)

########################################
# File download link
########################################
def filedownload(df):
    csv = df.to_csv(index=False)
    b64 = base64.b64encode(csv.encode()).decode()
    href = f'<a href="data:file/csv;base64,{b64}" download="prediction.csv">Download Predictions</a>'
    return href

########################################
# Model predictions
########################################
def build_model(input_data, smiles_list):
    model_file = "/Users/muhammadali/PycharmProjects/pythonProject13/MAOB_model.pkl"
    load_model = pickle.load(open(model_file, 'rb'))
    prediction = load_model.predict(input_data)

    st.header('**Prediction output**')
    df_result = pd.DataFrame({
        'SMILES': smiles_list,
        'pIC50': prediction
    })
    st.write(df_result)
    st.markdown(filedownload(df_result), unsafe_allow_html=True)

