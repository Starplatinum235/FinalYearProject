########################################
# Main prediction process
########################################
if st.sidebar.button('Predict'):
    # Read the uploaded file
    df_input = pd.read_table(uploaded_file, header=None, sep=None, engine='python')

    # Keep only the first column (SMILES)
    df_input = df_input.iloc[:, [0]]
    df_input.columns = ['SMILES']

    # Save input as 'molecule.smi'
    df_input.to_csv('/Users/muhammadali/PycharmProjects/pythonProject13/molecule.smi', sep='\t', header=False, index=False)

    st.subheader('**Original input data**')
    st.write(df_input)

    # Calculate descriptors
    with st.spinner("Calculating descriptors..."):
        desc_calc()

    # Read descriptors
    output_file = "/Users/muhammadali/PycharmProjects/pythonProject13/descriptors_output.csv"
    st.subheader('**Calculated molecular descriptors**')
    if os.path.exists(output_file):
        desc = pd.read_csv(output_file)
        st.write(desc)
        st.write(f"**Descriptors shape:** {desc.shape}")
    else:
        st.error("Descriptors file not found. PaDEL might have failed.")
        st.stop()

    # Subset descriptors for the model
    descriptor_list_file = "/Users/muhammadali/PycharmProjects/pythonProject13/descriptor_list.csv"
    if os.path.exists(descriptor_list_file):
        Xlist = list(pd.read_csv(descriptor_list_file).columns)
        desc_subset = desc[Xlist]
        st.subheader('**Subset of descriptors**')
        st.write(desc_subset)
        st.write(f"**Subset shape:** {desc_subset.shape}")
    else:
        st.error("descriptor_list.csv not found. Please ensure the file is present.")
        st.stop()

    # Predict using the model
    build_model(desc_subset, df_input['SMILES'])

else:
    st.info("Upload a file in the sidebar to begin!")
